"""Write src/tag-family.ts: tagStandard41h12's codes and bit layout, from the AprilTag library's own family table.

    uv run --project python/vision python packages/faces/scripts/tag-family.py

Run from the repo root. The table never changes, so the output is committed and this is only run again to check it.
"""

import ctypes
from pathlib import Path

from snapscript_vision.tags import FAMILY, _family

f = _family()
assert f.total_width == 9 and f.width_at_border == 5 and f.reversed_border, "the layout below assumes these"
bit_x = [ctypes.c_int32(f.bit_x[i]).value for i in range(f.nbits)]
bit_y = [ctypes.c_int32(f.bit_y[i]).value for i in range(f.nbits)]
codes = [f"{f.codes[i]:011x}" for i in range(f.ncodes)]
lines = [codes[i:i + 10] for i in range(0, len(codes), 10)]

out = Path(__file__).parent.parent / "src" / "tag-family.ts"
out.write_text(
    f"// Generated by scripts/tag-family.py from the AprilTag library's {FAMILY} table. Don't edit.\n\n"
    f"/** Each bit's cell, from the 5 × 5 border's top-left, most significant bit first. */\n"
    f"export const BIT_X: readonly number[] = {bit_x};\n"
    f"export const BIT_Y: readonly number[] = {bit_y};\n\n"
    f"/** The {f.ncodes} codes, {f.nbits} bits each, in hex. */\n"
    f"export const CODES: readonly string[] = `\n"
    + "\n".join(" ".join(l) for l in lines)
    + "\n`.trim().split(/\\s+/);\n"
)
print(f"wrote {out} ({f.ncodes} codes)")
