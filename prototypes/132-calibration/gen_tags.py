"""PROTOTYPE (#132, from #129 and #128), throwaway: write tags.js, the 9×9 bits of the real tagStandard41h12 markers (IDs 0-2114)
the printed cards, the ruler page and the projector use (print.html, app/table.html). Same source as #46's make_sheets.py.

    uv run gen_tags.py
"""

import json
from pathlib import Path
from urllib.request import urlopen

from PIL import Image

HERE = Path(__file__).parent
URL = "https://raw.githubusercontent.com/AprilRobotics/apriltag-imgs/master/tagStandard41h12/tag41_12_{:05d}.png"
PAGE_IDS = range(2000, 2010)   # page markers
CALIB_IDS = range(2100, 2112)  # tags the projector shows on the bare table (step 1)
DRIFT_IDS = range(2050, 2054)  # tags the projector keeps in the work area's corners, to notice a knocked stand
FACE_IDS = range(2060, 2072)   # tags the projector shows on the calibration cards' faces (step 2)
RULER_IDS = [2080, 2081]       # the ruler page's two markers
CAL_CARD_IDS = range(1100, 1106)  # calibration cards: a marker and a blank face, raised on 4U bases
CARD_IDS = [int(i) for i in json.loads((HERE / "cards.json").read_text())["cards"]]  # paper test cards


def bits(i: int) -> list[str]:
    path = HERE / ".tags" / f"{i:05d}.png"
    if not path.exists():
        path.parent.mkdir(exist_ok=True)
        path.write_bytes(urlopen(URL.format(i)).read())
    im = Image.open(path).convert("RGBA")
    return ["".join("1" if im.getpixel((x, y))[3] > 0 and im.getpixel((x, y))[0] < 128 else "0" for x in range(9)) for y in range(9)]


tags = {i: bits(i) for i in [*PAGE_IDS, *CALIB_IDS, *DRIFT_IDS, *FACE_IDS, *RULER_IDS, *CAL_CARD_IDS, *CARD_IDS]}
(HERE / "tags.js").write_text("// PROTOTYPE (#132): generated by gen_tags.py. id -> 9 rows of 9 cells, 1 = black.\nconst TAGS = " + json.dumps(tags) + ";\n")
print(f"wrote {len(tags)} tags")
